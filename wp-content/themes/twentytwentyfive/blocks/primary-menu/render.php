<?php
/**
 * Render the classic primary menu selected by Polylang for the current language.
 *
 * @package Twenty_Twenty_Five
 */

$item_class_filter = static function ( $classes ) {
	$classes[] = 'wp-block-navigation-item';
	return array_values( array_unique( $classes ) );
};

$link_attributes_filter = static function ( $attributes ) {
	$classes = preg_split( '/\s+/', $attributes['class'] ?? '', -1, PREG_SPLIT_NO_EMPTY );
	$classes[] = 'wp-block-navigation-item__content';
	$attributes['class'] = implode( ' ', array_unique( $classes ) );
	return $attributes;
};

add_filter( 'nav_menu_css_class', $item_class_filter, 10, 4 );
add_filter( 'nav_menu_link_attributes', $link_attributes_filter, 10, 4 );

try {
	$menu = wp_nav_menu(
		array(
			'theme_location' => 'pilloway-primary',
			'container'      => false,
			'echo'           => false,
			'fallback_cb'    => false,
			'depth'          => 1,
			'items_wrap'     => '%3$s',
			'link_before'    => '<span class="wp-block-navigation-item__label">',
			'link_after'     => '</span>',
			'item_spacing'   => 'discard',
		)
	);
} finally {
	remove_filter( 'nav_menu_css_class', $item_class_filter, 10 );
	remove_filter( 'nav_menu_link_attributes', $link_attributes_filter, 10 );
}

if ( is_string( $menu ) ) {
	echo $menu; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_nav_menu().
}
